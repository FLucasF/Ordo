"""Builds lib/features/common/emoji_data.dart: every emoji of Unicode's emoji-test.txt (skin tones
included) in the picker's eight categories, each with its Portuguese words for the search, from
CLDR's annotations (plus the words of the picker's old hand-made list, tool/emoji_extra_words.json).

Usage: python tool/make_emoji_asset.py <emoji-test.txt> <annotations pt.json> <annotationsDerived pt.json>

The sources: https://unicode.org/Public/emoji/16.0/emoji-test.txt and, from
https://github.com/unicode-org/cldr-json, cldr-annotations-full/annotations/pt/annotations.json and
cldr-annotations-derived-full/annotationsDerived/pt/annotations.json.
"""

import json
import re
import sys

# Newer than this, Windows and most phones still draw a box.
MAX_VERSION = 15.1

# emoji-test.txt's groups, in the picker's categories (Component is left out: tones and hair alone).
CATEGORIES = [
    ['Smileys & Emotion', 'People & Body'],
    ['Animals & Nature'],
    ['Food & Drink'],
    ['Activities'],
    ['Travel & Places'],
    ['Objects'],
    ['Symbols'],
    ['Flags'],
]


def old_words(path):
    """The words the hand-made list had for each emoji ("💪": ["forca", "academia", "treino"])."""
    return json.load(open(path, encoding='utf-8'))


def main(test_path, annotations_path, derived_path, extra_path, out_path):
    names = {}
    for path in (annotations_path, derived_path):
        data = json.load(open(path, encoding='utf-8'))
        root = data.get('annotations') or data.get('annotationsDerived')
        for key, value in root['annotations'].items():
            names[key] = value
    old = old_words(extra_path)

    groups = {g: [] for cat in CATEGORIES for g in cat}
    group = None
    for line in open(test_path, encoding='utf-8'):
        if line.startswith('# group:'):
            group = line.split(':', 1)[1].strip()
            continue
        m = re.match(r'^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)', line)
        if not m or group not in groups:
            continue
        emoji, version = m.group(1), float(m.group(2))
        if version > MAX_VERSION:
            continue
        info = names.get(emoji) or names.get(emoji.replace('️', '')) or {}
        words = []
        for w in info.get('tts', []) + info.get('default', []) + old.get(emoji, []):
            for part in w.lower().replace('|', ' ').split():
                if part not in words:
                    words.append(part)
        groups[group].append(emoji + (' ' + ' '.join(words) if words else ''))

    def literal(s):
        return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"

    total = 0
    out = [
        '// Generated by tool/make_emoji_asset.py from Unicode emoji-test.txt 16.0 and CLDR\'s Portuguese',
        '// annotations; do not edit. Each entry: the emoji, then the words that find it.',
        '',
        '/// The picker\'s categories, in its order: Pessoas e Corpo, Natureza, Comida, Atividades, Viagem,',
        '/// Objetos, Símbolos, Bandeiras.',
        'const emojiCategories = <List<String>>[',
    ]
    for cat in CATEGORIES:
        entries = [e for g in cat for e in groups[g]]
        total += len(entries)
        out.append('  [')
        out.extend('    ' + literal(e) + ',' for e in entries)
        out.append('  ],')
    out.append('];')
    open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(total, 'emojis;', [sum(len(groups[g]) for g in cat) for cat in CATEGORIES])


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3], 'tool/emoji_extra_words.json', 'lib/features/common/emoji_data.dart')
